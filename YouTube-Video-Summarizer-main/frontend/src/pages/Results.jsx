import { useEffect, useState } from "react";
import { Navigate, Link, useLocation } from "react-router-dom";
import { jsPDF } from "jspdf";

function wordCount(text) {
  return text?.trim() ? text.trim().split(/\s+/).length : 0;
}

export function Results() {
  const location = useLocation();
  const state = location.state;
  const [toast, setToast] = useState("");

  useEffect(() => {
    if (!toast) return;
    const timer = setTimeout(() => setToast(""), 3000);
    return () => clearTimeout(timer);
  }, [toast]);

  if (!state) return <Navigate to="/" replace />;

  const { url, method, percentage, result } = state;
  const totalWords = wordCount(result.text);
  const summaryWords = wordCount(result.summary);
  const compression = totalWords ? ((summaryWords / totalWords) * 100).toFixed(1) : "0.0";

  const copy = (text) => {
    navigator.clipboard.writeText(text || "");
    setToast("Content copied to clipboard!");
  };

  const downloadResults = () => {
    const doc = new jsPDF();
    doc.setFont("Courier", "normal");
    doc.setFontSize(12);

    const margin = 15;
    let y = margin;

    function addSection(title, content) {
      doc.setFont(undefined, "bold");
      doc.text(title, margin, y);
      y += 6;
      doc.setFont(undefined, "normal");

      const lines = doc.splitTextToSize(content, 180);
      for (const line of lines) {
        if (y > 280) {
          doc.addPage();
          y = margin;
        }
        doc.text(line, margin, y);
        y += 6;
      }
      y += 6;
    }

    addSection("YouTube Video Summary Report", "");
    addSection("Video URL:", url);
    addSection("Method:", method.charAt(0).toUpperCase() + method.slice(1));
    addSection("Summary Length:", `${percentage}%`);
    addSection("Generated:", new Date().toLocaleString());
    addSection("SUMMARY", result.summary || "No summary generated.");
    addSection("FULL TRANSCRIPT", result.text || "No transcript available.");
    addSection("Generated by YouTube Summarizer", "");

    doc.save(`youtube_summary_${new Date().toISOString().split("T")[0]}.pdf`);
    setToast("Results downloaded as PDF!");
  };

  return (
    <div className="card">
      <h1>Summary Results</h1>

      <div className="result-meta">
        <a href={url} target="_blank" rel="noreferrer">{url}</a>
        <div className="badges">
          <span className="badge">Method: {method === "abstractive" ? "Abstractive" : "Extractive"}</span>
          <span className="badge">Summary Length: {percentage}%</span>
          <span className="badge badge-success">Status: Completed</span>
        </div>
      </div>

      <div className="stats-row">
        <div className="stat">
          <div className="stat-value">{totalWords}</div>
          <div className="stat-label">Total Words</div>
        </div>
        <div className="stat">
          <div className="stat-value">{summaryWords}</div>
          <div className="stat-label">Summary Words</div>
        </div>
        <div className="stat">
          <div className="stat-value">{compression}%</div>
          <div className="stat-label">Compression Ratio</div>
        </div>
      </div>

      <div className="result-section">
        <div className="result-section-header">
          <h2>⭐ Summary</h2>
          <button className="link-btn" onClick={() => copy(result.summary)}>📋 Copy</button>
        </div>
        <div className="result-box">{result.summary || <em>No summary generated.</em>}</div>
      </div>

      <div className="result-section">
        <div className="result-section-header">
          <h2>📝 Full Transcript</h2>
          <button className="link-btn" onClick={() => copy(result.text)}>📋 Copy</button>
        </div>
        <div className="result-box">{result.text || <em>No transcript available.</em>}</div>
      </div>

      <div className="result-actions">
        <Link to="/" className="submit-btn secondary-btn">🔁 Summarize Another Video</Link>
        <button className="submit-btn" onClick={downloadResults}>💾 Download Results</button>
      </div>

      {toast && <div className="toast">{toast}</div>}
    </div>
  );
}
